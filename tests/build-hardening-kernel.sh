set -eu
test "$#" = 1 || { echo "usage: $0 /path/to/linux-source" >&2; exit 2; }
cd "$1"
make tinyconfig
scripts/config -d SLUB_TINY
for opt in \
  64BIT SMP MODULES MODULE_UNLOAD MULTIUSER PRINTK BUG ELFCORE \
  BINFMT_ELF BINFMT_SCRIPT FUTEX FILE_LOCKING POSIX_TIMERS EPOLL \
  SIGNALFD TIMERFD EVENTFD SYSCTL PROC_FS SYSFS TMPFS SHMEM \
  DEVTMPFS DEVTMPFS_MOUNT BLK_DEV_INITRD RD_GZIP TTY \
  SERIAL_8250 SERIAL_8250_CONSOLE UNIX NET INET IPV6 WIREGUARD \
  PCI ACPI NETDEVICES NET_UDP_TUNNEL DST_CACHE NAMESPACES NET_NS USER_NS \
  PACKET CRYPTO CRYPTO_ALGAPI CRYPTO_LIB_CURVE25519 \
  CRYPTO_LIB_CHACHA20POLY1305 DEBUG_KERNEL DEBUG_SPINLOCK DEBUG_MUTEXES \
  DEBUG_ATOMIC_SLEEP PROVE_LOCKING DEBUG_LOCK_ALLOC STACKTRACE SLUB_DEBUG \
  KASAN KASAN_GENERIC KASAN_INLINE DEBUG_FS FAULT_INJECTION FAILSLAB \
  FAULT_INJECTION_DEBUG_FS KALLSYMS KALLSYMS_ALL \
  FAULT_INJECTION_STACKTRACE_FILTER X86_MPPARSE IKCONFIG IKCONFIG_PROC
do
  scripts/config -e "$opt"
done
scripts/config --set-val NR_CPUS 2
scripts/config --set-str LOCALVERSION '-awg-lab'
make olddefconfig
make -j"${JOBS:-8}" bzImage modules
